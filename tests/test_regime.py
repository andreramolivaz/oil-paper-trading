def _real_features() -> pd.DataFrame | None:
    """Build the feature frame from the captured market-data fixture, or None when it is not there."""
    try:
        fixtures = importlib.import_module("engine.data.fixtures")
    except ImportError:
        return None
    loader = next(
        (
            getattr(fixtures, name)
            for name in ("fixture_market_data", "load_fixture_market_data", "load_market_data", "market_data")
            if callable(getattr(fixtures, name, None))
        ),
        None,
    )
    if loader is None:
        return None
    try:
        md = loader()
        from engine.features.builder import FullFeatureBuilder

        asof = pd.Timestamp(md.prices.index[-1]).tz_localize("UTC") + pd.Timedelta(days=1)
        return FullFeatureBuilder().build(md, asof.to_pydatetime())
    except Exception:  # pragma: no cover - the fixture API is owned by another module
        return None


