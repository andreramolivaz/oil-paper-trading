def test_history_is_byte_identical_when_future_rows_are_appended() -> None:
    """THE causality test: appending 200 future rows must not move a single past number."""
    long_frame, _ = make_synthetic_features(N_ROWS + 200)
    short_frame = long_frame.iloc[:N_ROWS]
    a = FullRegimeModel().history(short_frame)
