def test_transition_when_probabilities_are_flat() -> None:
    """Overlapping regimes => flat posterior => "Transizione" with the underlying distribution reported."""
    frame, _ = make_synthetic_features(500, spread=8.0)
    model = FullRegimeModel(FAST_CONFIG)
    hist = model.history(frame)
    tail = hist.iloc[FAST_CONFIG["min_obs"] :]
    assert float(tail[cat.REGIME_CONF].min()) < model.min_confidence
    flat = tail[(tail[cat.REGIME_CONF] > 0.0) & (tail[cat.REGIME_CONF] < model.min_confidence)]
    assert len(flat) > 0, "the overlapping frame produced no low-confidence day"
    assert (flat[cat.REGIME_LABEL] == LABEL_TRANSITION).all()
    assert (flat[cat.REGIME_ID] == -1).all()


def test_transition_when_confidence_is_below_the_threshold() -> None:
    frame, _ = make_synthetic_features(500)
    # An unsatisfiable threshold: no regime can ever pass it, which is the brief's "nessun regime supera la
    # soglia di confidenza" case. The planted regimes are so separable that any threshold <= 1 is passed.
    strict = FullRegimeModel({**FAST_CONFIG, "min_confidence": 1.0 + 1e-9})
    hist = strict.history(frame)
    tail = hist.iloc[FAST_CONFIG["min_obs"] :]
    assert (tail[cat.REGIME_LABEL] == LABEL_TRANSITION).all()
    assert (tail[cat.REGIME_ID] == -1).all()
    state = strict.infer(frame, _utc(frame.index[-1]))
    assert state.label == LABEL_TRANSITION
    assert state.regime_id == -1
    assert state.is_transition
    # the underlying distribution is still reported
    assert state.probabilities and abs(sum(state.probabilities.values()) - 1.0) < 1e-6
    assert state.confidence == pytest.approx(max(state.probabilities.values()))


def test_reported_regimes_respect_the_thresholds(fitted: tuple[FullRegimeModel, pd.DataFrame, float]) -> None:
    """A row that names a regime must clear BOTH gates; a transition row must fail at least one."""
    model, hist, _ = fitted
    named = hist[hist[cat.REGIME_LABEL] != LABEL_TRANSITION]
    assert len(named) > 0
    assert (named[cat.REGIME_CONF] >= model.min_confidence).all()
    assert (named[cat.BOCPD_CP_PROB] <= model.cp_threshold).all()
    assert (named[cat.REGIME_ID] >= 0).all()
    trans = hist[hist[cat.REGIME_LABEL] == LABEL_TRANSITION]
    failed = (trans[cat.REGIME_CONF] < model.min_confidence) | (trans[cat.BOCPD_CP_PROB] > model.cp_threshold)
    assert failed.all()
    # a uniform posterior over 3 states peaks at 1/3, well below the default threshold
    assert model.min_confidence > 1.0 / 3.0


