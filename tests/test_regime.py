def test_walk_forward_recovers_planted_regimes(
    synthetic: tuple[pd.DataFrame, pd.Series], fitted: tuple[FullRegimeModel, pd.DataFrame, float]
) -> None:
    frame, truth = synthetic
    model, hist, _ = fitted
    details = model._details
    assert details is not None
    # Out-of-sample days only: the first training window is necessarily labelled in-sample.
    oos = ~details.warmup.to_numpy()
    # The planted shock aftermath is legitimately "Shock/crash", which is not one of the three planted
    # regime labels, so those days are excluded from the recovery share.
    shock = np.zeros(len(frame), dtype=bool)
    shock[SHOCK_AT : SHOCK_AT + SHOCK_LEN + 5] = True
    scored = oos & ~shock
    expected = truth.map(TRUTH_TO_LABEL).to_numpy()
    hit = hist[cat.REGIME_LABEL].to_numpy()[scored] == expected[scored]
    share = float(hit.mean())
    logging.getLogger(__name__).info("regime recovery share = %.4f on %d days", share, int(scored.sum()))
    print(f"\nplanted-regime recovery share: {share:.4f} on {int(scored.sum())} out-of-sample days")
    assert share >= 0.70, f"recovery share {share:.3f} below the 70% floor"


def test_planted_shock_is_flagged_as_a_transition(fitted: tuple[FullRegimeModel, pd.DataFrame, float]) -> None:
    """The planted shock is handled by the change-point path, not by a dedicated HMM state.

    Fifteen shock days out of 2 500 never buy their own state: BIC refuses the extra k. That is the right
    outcome -- the detector fires, the model says "Transizione" and the allocator cuts risk -- while
    LABEL_SHOCK_CRASH is reserved for a crash that PERSISTS long enough to be a regime (the labelling rule
    itself is covered by `test_label_states_precedence_rules`).
    """
    _, hist, _ = fitted
    window = hist.iloc[SHOCK_AT : SHOCK_AT + 10]
    assert (window[cat.REGIME_LABEL] == LABEL_TRANSITION).any()
    assert (window[cat.REGIME_ID] == -1).any()
    assert float(window[cat.BOCPD_CP_PROB].max()) > 0.5


def test_state_id_keeps_its_label_across_refits(fitted: tuple[FullRegimeModel, pd.DataFrame, float]) -> None:
    model, _, _ = fitted
    result = model.hmm.result
    assert result is not None
    assert len(result.fits) > 5  # several refit boundaries in the sample
    per_id: dict[int, set[str]] = collections.defaultdict(set)
    for fit in result.fits:
        for cid, label in zip(fit.canonical_ids, label_states(fit.means, fit.feature_names)):
            per_id[cid].add(label)
    bad = {cid: labels for cid, labels in per_id.items() if len(labels) > 1}
    assert not bad, f"canonical state ids changed meaning across refits: {bad}"


def test_two_states_may_share_a_label_and_probabilities_add(
    fitted: tuple[FullRegimeModel, pd.DataFrame, float],
) -> None:
    model, hist, _ = fitted
    result = model.hmm.result
    assert result is not None
    shared = None
    for fit in result.fits:
        labels = label_states(fit.means, fit.feature_names)
        counts = collections.Counter(labels)
        dup = [label for label, c in counts.items() if c > 1]
        if dup:
            shared = (fit, labels, dup[0])
            break
    assert shared is not None, "no fit assigned the same label to two states; cannot check the sum rule"
    fit, labels, label = shared
    rows = result.fit_date == fit.fit_date
    cids = [cid for cid, lb in zip(fit.canonical_ids, labels) if lb == label]
    direct = result.posteriors.loc[rows, cids].sum(axis=1)
    reported = hist.loc[rows, prob_column(label)]
    pd.testing.assert_series_equal(direct, reported, check_names=False, check_exact=True)


