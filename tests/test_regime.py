# (mean, sd) per planted regime. Deliberately separable but overlapping at one sigma.
SPECS: dict[str, dict[str, tuple[float, float]]] = {
    LOW: {
        "ret1": (0.0002, 0.008),
        "ret21": (0.005, 0.012),
        "rv": (0.18, 0.015),
        "slope": (0.000, 0.004),
        "tsmom": (0.0, 0.30),
        "geo": (0.15, 0.03),
        "stocks": (0.000, 0.015),
    },
    HIGH: {
        "ret1": (0.0020, 0.032),
        "ret21": (0.045, 0.030),
        "rv": (0.55, 0.050),
        "slope": (0.080, 0.010),
        "tsmom": (1.2, 0.40),
        "geo": (0.85, 0.05),
        "stocks": (-0.060, 0.015),
    },
    DOWN: {
        "ret1": (-0.0024, 0.018),
        "ret21": (-0.050, 0.020),
        "rv": (0.30, 0.025),
        "slope": (-0.060, 0.008),
        "tsmom": (-1.2, 0.40),
        "geo": (0.20, 0.04),
        "stocks": (0.070, 0.015),
    },
}

_BLOCKS: list[tuple[str, int]] = [
    (LOW, 260),
    (HIGH, 200),
    (LOW, 180),
    (DOWN, 220),
    (HIGH, 190),
    (LOW, 240),
    (DOWN, 210),
    (HIGH, 200),
    (LOW, 230),
    (DOWN, 190),
    (LOW, 200),
    (HIGH, 180),
]
SHOCK_AT = 1600  # inside a HIGH block, far from any planted regime boundary
SHOCK_LEN = 15
QUIET_SLICES = [slice(1100, 1280), slice(1750, 1900)]  # inside single LOW blocks
N_ROWS = 2500


def _truth(n: int) -> list[str]:
    seq: list[str] = []
    while len(seq) < n:
        for name, length in _BLOCKS:
            seq += [name] * length
    return seq[:n]


def make_synthetic_features(n: int = N_ROWS, seed: int = 7, spread: float = 1.0) -> tuple[pd.DataFrame, pd.Series]:
    """SYNTHETIC feature frame with three planted regimes and one planted shock. Not market data.

    `spread` multiplies every standard deviation: spread=1 gives well separated regimes, a large spread
    makes them overlap so much that the filtered posterior is flat (used to test the transition rule).
    """
    rng = np.random.default_rng(seed)
    truth = _truth(n)
    keys = ("ret1", "ret21", "rv", "slope", "tsmom", "geo", "stocks")
    rows = {k: np.empty(n, dtype="float64") for k in keys}
    for i, name in enumerate(truth):
        spec = SPECS[name]
        for k in keys:
            mean, sd = spec[k]
            rows[k][i] = rng.normal(mean, sd * spread)
    # planted shock: one violent day plus a three-week aftermath of high vol and negative one-month return
    if 0 <= SHOCK_AT < n:
        rows["ret1"][SHOCK_AT] = -0.22
        end = min(n, SHOCK_AT + SHOCK_LEN)
        rows["ret21"][SHOCK_AT:end] -= 0.18
        rows["rv"][SHOCK_AT:end] += 0.45
    idx = pd.bdate_range("2014-01-01", periods=n)
    frame = pd.DataFrame(
        {
            cat.RET_1: rows["ret1"],
            cat.RET_21: rows["ret21"],
            cat.RV_YZ_21: np.maximum(rows["rv"], 0.02),
            cat.SLOPE_M1_M6: rows["slope"],
            cat.VRP: np.nan,  # all-NaN on purpose: exercises the "drop the empty column" path
            cat.TSMOM_63: rows["tsmom"],
            cat.GEO_INDEX: np.clip(rows["geo"], 0.0, 1.0),
            cat.CRUDE_STOCKS_VS_5Y: rows["stocks"],
        },
        index=idx,
    )
    return frame, pd.Series(truth, index=idx, name="planted")


