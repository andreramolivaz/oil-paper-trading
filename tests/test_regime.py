def _utc(day: pd.Timestamp) -> datetime:
    """Settlement timestamp (UTC) of a tz-naive trading date, as `infer` expects."""
    from engine.core.timeutil import settlement_ts

    return settlement_ts(pd.Timestamp(day).date())
