    model.history(frame)
    details = model._details
    result = model.hmm.result
    assert details is not None and result is not None
    assert result.slope_missing is False  # the column is not empty across the whole frame...
    assert result.fits[0].slope_missing is True  # ...but it is empty in the first training window
    assert result.fits[-1].slope_missing is False
    assert bool(details.approx.iloc[FAST_CONFIG["min_obs"]]) is True
    assert bool(details.approx.iloc[-1]) is False
    assert model.infer(frame, _utc(frame.index[-1])).approx is False


