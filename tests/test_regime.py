def test_approx_flag_follows_the_active_fit() -> None:
    """A window where the slope column exists but is empty is as approximate as one without the column."""
    frame, _ = make_synthetic_features(500)
    frame[cat.SLOPE_M1_M6] = np.where(np.arange(len(frame)) >= 300, frame[cat.SLOPE_M1_M6], np.nan)
